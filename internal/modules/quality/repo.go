// repository is all MongoDB access for the quality module. It owns qc_results
// and — as the safety-gate verdict writer (blueprint §8.3) — performs the
// documented cross-collection status write onto bmc_lots and
// processing_batches. No other module may flip those gate statuses.
type repository struct {
	results      *mongo.Collection
	bmcLots      *mongo.Collection
	batches      *mongo.Collection
	counters     *mongo.Collection
	certificates *mongo.Collection
	consignments *mongo.Collection // per-samiti batches: F7 QC queue reads + the sanctioned QC verdict write
	// Per-samiti batch QC (F7): this module owns the consignment_qc results and
	// the auto-minted consignment batch QRs.
	consignmentQC *mongo.Collection
	batchQRs      *mongo.Collection
}

// newRepository binds the repository to its collections.
func newRepository(db *mongo.Database) *repository {
	return &repository{
		results:       db.Collection(mongodb.CollQCResults),
		bmcLots:       db.Collection(mongodb.CollBMCLots),
		batches:       db.Collection(mongodb.CollBatches),
		counters:      db.Collection(mongodb.CollCounters),
		certificates:  db.Collection(mongodb.CollQCCertificates),
		consignments:  db.Collection(mongodb.CollConsignments),
		consignmentQC: db.Collection(mongodb.CollConsignmentQC),
		batchQRs:      db.Collection(mongodb.CollConsignmentBatchQRs),
	}
}

// societyContribution is one DCS's share of a batch, aggregated from the
// consignments that fed it (via its BMC lots) — litres poured, pour count and
// the earliest collection date.
type societyContribution struct {
	Litres      float64
	PourCount   int
	CollectedOn string
}

// consignmentContributions resolves a batch's BMC lots to the consignments that
// fed them and aggregates, per contributing DCS, the litres, pour count and
// earliest collection date — the weighted per-society breakdown the trace-back
// screen renders (§7.4 honest set-valued pooling). Read-only across bmc_lots and
// dcs_consignments (sanctioned by the trace-back use case).
func (r *repository) consignmentContributions(ctx context.Context, bmcLotIDs []primitive.ObjectID) (map[primitive.ObjectID]societyContribution, error) {
	out := map[primitive.ObjectID]societyContribution{}
	if len(bmcLotIDs) == 0 {
		return out, nil
	}
	// 1) BMC lots → the union of their consignment ids.
	lotCur, err := r.bmcLots.Find(ctx,
		bson.D{{Key: "_id", Value: bson.D{{Key: "$in", Value: bmcLotIDs}}}},
		options.Find().SetProjection(bson.D{{Key: "consignment_ids", Value: 1}}))
	if err != nil {
		return nil, httpx.Internal(fmt.Errorf("trace-back: load bmc lots: %w", err))
	}
	var lotRows []struct {
		ConsignmentIDs []primitive.ObjectID `bson:"consignment_ids"`
	}
	if err := lotCur.All(ctx, &lotRows); err != nil {
		return nil, httpx.Internal(fmt.Errorf("trace-back: decode bmc lots: %w", err))
	}
	seen := map[primitive.ObjectID]struct{}{}
	consIDs := make([]primitive.ObjectID, 0)
	for _, lr := range lotRows {
		for _, id := range lr.ConsignmentIDs {
			if _, ok := seen[id]; ok {
				continue
			}
			seen[id] = struct{}{}
			consIDs = append(consIDs, id)
		}
	}
	if len(consIDs) == 0 {
		return out, nil
	}
	// 2) Consignments → per-DCS litres/pour-count/date.
	consCur, err := r.consignments.Find(ctx,
		bson.D{{Key: "_id", Value: bson.D{{Key: "$in", Value: consIDs}}}},
		options.Find().SetProjection(bson.D{
			{Key: "dcs_id", Value: 1}, {Key: "total_quantity_litres", Value: 1},
			{Key: "pour_ids", Value: 1}, {Key: "date", Value: 1},
		}))
	if err != nil {
		return nil, httpx.Internal(fmt.Errorf("trace-back: load consignments: %w", err))
	}
	var consRows []struct {
		DCSID   primitive.ObjectID   `bson:"dcs_id"`
		Litres  float64              `bson:"total_quantity_litres"`
		PourIDs []primitive.ObjectID `bson:"pour_ids"`
		Date    string               `bson:"date"`
	}
	if err := consCur.All(ctx, &consRows); err != nil {
		return nil, httpx.Internal(fmt.Errorf("trace-back: decode consignments: %w", err))
	}
	for _, cr := range consRows {
		c := out[cr.DCSID]
		c.Litres += cr.Litres
		c.PourCount += len(cr.PourIDs)
		if c.CollectedOn == "" || (cr.Date != "" && cr.Date < c.CollectedOn) {
			c.CollectedOn = cr.Date
		}
		out[cr.DCSID] = c
	}
	return out, nil
}

// insertResult stores a new QC result document (its _id is pre-generated by
// the service so provenance refs and the gate write share one ID).
func (r *repository) insertResult(ctx context.Context, res *domain.QCResult) error {
	if _, err := r.results.InsertOne(ctx, res); err != nil {
		return httpx.Internal(fmt.Errorf("insert qc result: %w", err))
	}
	return nil
}

// setResultProvenanceSeq stamps the ledger sequence onto a stored result.
func (r *repository) setResultProvenanceSeq(ctx context.Context, resultID primitive.ObjectID, seq int64) error {
	_, err := r.results.UpdateOne(ctx,
		bson.D{{Key: "_id", Value: resultID}},
		bson.D{{Key: "$set", Value: bson.D{{Key: "provenance_seq", Value: seq}}}},
	)
	if err != nil {
		return httpx.Internal(fmt.Errorf("set qc result provenance seq: %w", err))
	}
	return nil
}

// markResultSuperseded voids a result that lost the gate race — the subject's
// verdict came from a different, earlier result.
func (r *repository) markResultSuperseded(ctx context.Context, resultID primitive.ObjectID) error {
	_, err := r.results.UpdateOne(ctx,
		bson.D{{Key: "_id", Value: resultID}},
		bson.D{{Key: "$set", Value: bson.D{{Key: "superseded", Value: true}}}},
	)
	if err != nil {
		return httpx.Internal(fmt.Errorf("mark qc result superseded: %w", err))
	}
	return nil
}

// findResultByID returns one QC result or NotFound.
func (r *repository) findResultByID(ctx context.Context, resultID primitive.ObjectID) (*domain.QCResult, error) {
	var res domain.QCResult
	err := r.results.FindOne(ctx, bson.D{{Key: "_id", Value: resultID}}).Decode(&res)
	if errors.Is(err, mongo.ErrNoDocuments) {
		return nil, httpx.NotFound("qc result")
	}
	if err != nil {
		return nil, httpx.Internal(fmt.Errorf("find qc result: %w", err))
	}
	return &res, nil
}

// listResults returns a page of QC results, newest first, optionally filtered
// by subject (a zero subjectID means "no subject filter"). It also returns
// the total matching count for pagination meta.
func (r *repository) listResults(ctx context.Context, subjectType string, subjectID primitive.ObjectID, page httpx.Page) ([]domain.QCResult, int64, error) {
	filter := bson.D{}
	if subjectType != "" {
		filter = append(filter, bson.E{Key: "subject_type", Value: subjectType})
	}
	if !subjectID.IsZero() {
		filter = append(filter, bson.E{Key: "subject_id", Value: subjectID})
	}

	total, err := r.results.CountDocuments(ctx, filter)
	if err != nil {
		return nil, 0, httpx.Internal(fmt.Errorf("count qc results: %w", err))
	}

	cur, err := r.results.Find(ctx, filter, options.Find().
		SetSort(bson.D{{Key: "recorded_at", Value: -1}}).
		SetSkip(page.Offset).
		SetLimit(page.Limit),
	)
	if err != nil {
		return nil, 0, httpx.Internal(fmt.Errorf("list qc results: %w", err))
	}
	results := []domain.QCResult{}
	if err := cur.All(ctx, &results); err != nil {
		return nil, 0, httpx.Internal(fmt.Errorf("decode qc results: %w", err))
	}
	return results, total, nil
}

