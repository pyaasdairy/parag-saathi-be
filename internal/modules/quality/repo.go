// recordedTestNames returns the set of canonical test names already recorded
// for a subject across its non-superseded QC results. For a QC_PENDING subject
// this is typically empty, but it stays correct if a partial/superseded result
// exists — the queue then honestly reports which parameters are on file.
func (r *repository) recordedTestNames(ctx context.Context, subjectType string, subjectID primitive.ObjectID) (map[string]bool, error) {
	cur, err := r.results.Find(ctx, bson.D{
		{Key: "subject_type", Value: subjectType},
		{Key: "subject_id", Value: subjectID},
		{Key: "superseded", Value: bson.D{{Key: "$ne", Value: true}}},
	})
	if err != nil {
		return nil, httpx.Internal(fmt.Errorf("find qc results for subject %s: %w", subjectID.Hex(), err))
	}
	var results []domain.QCResult
	if err := cur.All(ctx, &results); err != nil {
		return nil, httpx.Internal(fmt.Errorf("decode qc results for subject: %w", err))
	}
	names := map[string]bool{}
	for _, res := range results {
		for _, t := range res.Tests {
			names[t.Name] = true
		}
	}
	return names, nil
}

// findCertificateByBatch returns the certificate already issued for a batch, or
// mongo.ErrNoDocuments when none exists — the idempotency guard behind a single
// certificate per batch.
func (r *repository) findCertificateByBatch(ctx context.Context, batchID primitive.ObjectID) (*domain.QCCertificate, error) {
	var cert domain.QCCertificate
	if err := r.certificates.FindOne(ctx, bson.D{{Key: "batch_id", Value: batchID}}).Decode(&cert); err != nil {
		return nil, err
	}
	return &cert, nil
}

// insertCertificate persists a new QC certificate document. The per-batch
// idempotency guard runs in the service before this insert; a certificate_number
// collision (unique index) still surfaces as a 409 so a retry storm cannot mint
// colliding certificates.
func (r *repository) insertCertificate(ctx context.Context, cert *domain.QCCertificate) error {
	if _, err := r.certificates.InsertOne(ctx, cert); err != nil {
		if mongo.IsDuplicateKeyError(err) {
			return httpx.Conflict("ALREADY_ISSUED", "a certificate has already been issued for this batch")
		}
		return httpx.Internal(fmt.Errorf("insert qc certificate: %w", err))
	}
	return nil
}

// nextCertificateSeq atomically increments and returns the per-stage QC
// certificate counter (counters collection, upsert-on-first-use). Counter
// keys are human-readable strings by design — they are not entity references.
func (r *repository) nextCertificateSeq(ctx context.Context, stage string) (int64, error) {
	var doc struct {
		Seq int64 `bson:"seq"`
	}
	err := r.counters.FindOneAndUpdate(ctx,
		bson.D{{Key: "_id", Value: "qc_certificate:" + stage}},
		bson.D{{Key: "$inc", Value: bson.D{{Key: "seq", Value: int64(1)}}}},
		options.FindOneAndUpdate().SetUpsert(true).SetReturnDocument(options.After),
	).Decode(&doc)
	if err != nil {
		return 0, httpx.Internal(fmt.Errorf("next qc certificate seq: %w", err))
	}
	return doc.Seq, nil
}
